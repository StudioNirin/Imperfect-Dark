/**
 * A loose sound file over the game's mix, for the title screen's cue.
 *
 * The game's own sounds are ROM bank samples, loaded and played by
 * src/lib/snd.c. That is the right path for them - the bank carries the
 * envelope, the key map, the loop and the sample - and this is deliberately
 * not a replacement for it. It is one file, for one cue: the title screen
 * says something is new after an update, and the sound it says it with is
 * the shortest way to say it.
 *
 * What this does is decode the file (WAV through SDL, MP3 through the
 * minimp3 already in the tree) to mono s16 at the game's output rate, and
 * hand the samples to audio.c, which mixes them into the buffers it queues.
 * Going through that path rather than straight to SDL keeps the cue under
 * the same mute, surround, queue limit and recorder as everything else, and
 * avoids the other way of doing it: queueing the file on its own would hold
 * the game's own audio back for as long as the file plays.
 *
 * The build also carries a copy (port/audio/title-screen.mp3, generated into
 * titleaudiodata.h), because an update replaces only the executable. A file
 * at data/sfx/title-screen.wav or .mp3 beside the game, or in a mod's sfx/,
 * wins over the built-in one.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <strings.h>
#include <SDL.h>
#include <ultra64.h>
#include "sndfile.h"
#include "fs.h"
#include "system.h"
#include "external/minimp3.h"
// Generated by CMake from port/audio/title-screen.mp3.
#include "titleaudiodata.h"

// The game's output rate (port/src/audio.c opens the device at 22020, and the
// N64's AI ran at the same rate). A file is resampled to this before it is
// mixed, so it plays at the pitch it was authored at.
#define SNDFILE_RATE 22020

// A little headroom: the file is added to a mix that is already carrying the
// game's own sounds, and a full-scale file on top of a full-scale mix would
// only clip.
#define SNDFILE_GAIN_NUM 3 // of 4

struct shot {
	s16 *samples; // mono, SNDFILE_RATE
	u32 frames;
	u32 pos;
};

static struct shot g_Shot;

static s16 clamp16(s32 v)
{
	if (v > 32767) {
		return 32767;
	}

	if (v < -32768) {
		return -32768;
	}

	return (s16)v;
}

/**
 * The mono samples at inRate, resampled to SNDFILE_RATE. A new buffer; the
 * caller frees the old one. 2:1 takes the pair's mean rather than every other
 * sample, which is a cheap half-band and keeps the top octave from folding
 * back; anything else is linear.
 */
static s16 *resampleMono(const s16 *in, u32 inFrames, u32 inRate, u32 *outFrames)
{
	const u32 outN = (u32)((u64)inFrames * SNDFILE_RATE / inRate);
	s16 *out;
	u32 i;

	*outFrames = 0;

	if (inRate == 0 || outN == 0) {
		return NULL;
	}

	out = malloc(outN * sizeof(s16));

	if (!out) {
		return NULL;
	}

	if (inRate == SNDFILE_RATE * 2) {
		for (i = 0; i < outN; i++) {
			const s32 a = in[i * 2];
			const s32 b = in[i * 2 + 1 < inFrames ? i * 2 + 1 : inFrames - 1];

			out[i] = (s16)((a + b) / 2);
		}
	} else {
		for (i = 0; i < outN; i++) {
			const f64 src = (f64)i * inRate / SNDFILE_RATE;
			const u32 idx = (u32)src;
			const f64 frac = src - (f64)idx;
			const s32 a = in[idx < inFrames ? idx : inFrames - 1];
			const s32 b = in[idx + 1 < inFrames ? idx + 1 : inFrames - 1];

			out[i] = clamp16(a + (s32)((b - a) * frac));
		}
	}

	*outFrames = outN;

	return out;
}

/** A WAV SDL has read, downmixed to mono and resampled. */
static s16 *wavToMono(const u8 *data, u32 len, u32 *outFrames, u32 *outRate)
{
	SDL_RWops *rw;
	SDL_AudioSpec spec;
	Uint8 *pcm = NULL;
	Uint32 pcmLen = 0;
	s16 *mono;
	u32 channels;
	u32 bytes;
	u32 frames;
	u32 i;
	u32 c;

	*outFrames = 0;
	*outRate = 0;

	rw = SDL_RWFromMem((void *)data, (int)len);

	if (!rw) {
		return NULL;
	}

	if (!SDL_LoadWAV_RW(rw, 1, &spec, &pcm, &pcmLen)) {
		sysLogPrintf(LOG_WARNING, "sndfile: not a WAV SDL can read: %s", SDL_GetError());
		return NULL;
	}

	channels = spec.channels;

	switch (spec.format) {
	case AUDIO_U8:
	case AUDIO_S8:
		bytes = 1;
		break;
	case AUDIO_S16SYS:
		bytes = 2;
		break;
	case AUDIO_S32SYS:
	case AUDIO_F32SYS:
		bytes = 4;
		break;
	default:
		sysLogPrintf(LOG_WARNING, "sndfile: WAV format 0x%x is not supported", spec.format);
		SDL_free(pcm);
		return NULL;
	}

	if (channels == 0 || spec.freq == 0) {
		SDL_free(pcm);
		return NULL;
	}

	frames = pcmLen / (bytes * channels);
	mono = malloc(frames * sizeof(s16));

	if (!mono) {
		SDL_free(pcm);
		return NULL;
	}

	for (i = 0; i < frames; i++) {
		s32 sum = 0;

		for (c = 0; c < channels; c++) {
			const u8 *p = pcm + (i * channels + c) * bytes;
			s32 v;

			switch (spec.format) {
			case AUDIO_U8:
				v = ((s32)p[0] - 128) << 8;
				break;
			case AUDIO_S8:
				v = ((s32)(s8)p[0]) << 8;
				break;
			case AUDIO_S16SYS:
				{
					s16 s;
					memcpy(&s, p, sizeof(s));
					v = s;
				}
				break;
			case AUDIO_S32SYS:
				{
					s32 s;
					memcpy(&s, p, sizeof(s));
					v = s >> 16;
				}
				break;
			default: // AUDIO_F32SYS
				{
					f32 f;
					memcpy(&f, p, sizeof(f));
					v = (s32)(f * 32767.0f);
				}
				break;
			}

			sum += v;
		}

		mono[i] = clamp16(sum / (s32)channels);
	}

	SDL_free(pcm);

	if (spec.freq != SNDFILE_RATE) {
		u32 resampled = 0;
		s16 *rs = resampleMono(mono, frames, spec.freq, &resampled);

		free(mono);
		mono = rs;
		frames = resampled;
	}

	*outFrames = frames;
	*outRate = spec.freq;

	return mono;
}

/** An MP3 in memory, decoded by the minimp3 the mixer already uses. */
static s16 *mp3ToMono(const u8 *data, u32 len, u32 *outFrames, u32 *outRate)
{
	mp3dec_t dec;
	mp3dec_frame_info_t info;
	s16 pcm[MINIMP3_MAX_SAMPLES_PER_FRAME];
	s16 *mono = NULL;
	u32 n = 0;
	u32 cap = 0;
	u32 pos = 0;
	u32 rate = 0;
	s32 channels = 0;

	*outFrames = 0;
	*outRate = 0;

	mp3dec_init(&dec);

	while (pos < len) {
		const s32 samples = mp3dec_decode_frame(&dec, data + pos, (int)(len - pos), pcm, &info);

		if (info.frame_bytes <= 0) {
			break;
		}

		if (samples > 0) {
			s32 i;

			if (rate == 0) {
				rate = info.hz;
				channels = info.channels;
			}

			if (channels <= 0) {
				free(mono);
				return NULL;
			}

			if (n + (u32)samples > cap) {
				s16 *grown;

				cap = (n + (u32)samples) * 2;
				grown = realloc(mono, cap * sizeof(s16));

				if (!grown) {
					free(mono);
					return NULL;
				}

				mono = grown;
			}

			for (i = 0; i < samples; i++) {
				s32 sum = 0;
				s32 c;

				for (c = 0; c < channels; c++) {
					sum += pcm[i * channels + c];
				}

				mono[n++] = clamp16(sum / channels);
			}
		}

		pos += (u32)info.frame_bytes;
	}

	if (mono == NULL || n == 0 || rate == 0) {
		free(mono);
		return NULL;
	}

	if (rate != SNDFILE_RATE) {
		u32 resampled = 0;
		s16 *rs = resampleMono(mono, n, rate, &resampled);

		free(mono);
		mono = rs;
		n = resampled;
	}

	*outFrames = n;
	*outRate = rate;

	return mono;
}

/** Take a shot: the previous one is ended, this one starts at its beginning. */
static s32 shotStart(s16 *samples, u32 frames, const char *how, u32 rate)
{
	if (samples == NULL || frames == 0) {
		free(samples);
		return 0;
	}

	sndFileStop();

	g_Shot.samples = samples;
	g_Shot.frames = frames;
	g_Shot.pos = 0;

	sysLogPrintf(LOG_NOTE, "sndfile: playing %s (%u Hz source, %.2f s, mono %d for the mix)",
			how, rate, (f32)frames / SNDFILE_RATE, SNDFILE_RATE);

	return 1;
}

s32 sndFilePlay(const char *path)
{
	char full[FS_MAXPATH + 1];
	u32 len = 0;
	u8 *data;
	s16 *mono = NULL;
	u32 frames = 0;
	u32 rate = 0;
	const char *dot;

	snprintf(full, sizeof(full), "%s", fsFullPath(path));

	if (fsFileSize(full) <= 0) {
		return 0;
	}

	data = fsFileLoad(full, &len);

	if (data == NULL || len == 0) {
		free(data);
		return 0;
	}

	dot = strrchr(full, '.');

	if (dot != NULL && strcasecmp(dot, ".wav") == 0) {
		mono = wavToMono(data, len, &frames, &rate);
	} else if (dot != NULL && strcasecmp(dot, ".mp3") == 0) {
		mono = mp3ToMono(data, len, &frames, &rate);
	} else {
		// An unknown extension: the two decoders can tell for themselves.
		mono = wavToMono(data, len, &frames, &rate);

		if (mono == NULL) {
			mono = mp3ToMono(data, len, &frames, &rate);
		}
	}

	free(data);

	if (mono == NULL || frames == 0) {
		sysLogPrintf(LOG_WARNING, "sndfile: could not decode %s", full);
		free(mono);
		return 0;
	}

	return shotStart(mono, frames, full, rate);
}

s32 sndFilePlayCue(const char *stem)
{
	char path[FS_MAXPATH + 1];

	snprintf(path, sizeof(path), "%s.wav", stem);

	if (sndFilePlay(path)) {
		return 1;
	}

	snprintf(path, sizeof(path), "%s.mp3", stem);

	if (sndFilePlay(path)) {
		return 1;
	}

	if (g_TitleScreenAudioBuiltInSize > 0) {
		u32 frames = 0;
		u32 rate = 0;
		s16 *mono = mp3ToMono(g_TitleScreenAudioBuiltIn, g_TitleScreenAudioBuiltInSize, &frames, &rate);

		if (mono != NULL && frames > 0) {
			return shotStart(mono, frames, "the built-in title sound", rate);
		}

		free(mono);
	}

	return 0;
}

s32 sndFileIsPlaying(void)
{
	return g_Shot.samples != NULL && g_Shot.pos < g_Shot.frames;
}

u32 sndFilePos(void)
{
	return g_Shot.pos;
}

void sndFileMix(s16 *buf, u32 frames, s32 channels, u32 pos)
{
	u32 i;

	if (g_Shot.samples == NULL || pos >= g_Shot.frames || channels < 2) {
		return;
	}

	if (frames > g_Shot.frames - pos) {
		frames = g_Shot.frames - pos;
	}

	for (i = 0; i < frames; i++) {
		const s32 s = (g_Shot.samples[pos + i] * SNDFILE_GAIN_NUM) >> 2;
		const s32 l = (s32)buf[i * channels] + s;
		const s32 r = (s32)buf[i * channels + 1] + s;

		buf[i * channels] = (s16)clamp16(l);
		buf[i * channels + 1] = (s16)clamp16(r);
	}
}

void sndFileAdvance(u32 frames)
{
	if (g_Shot.samples == NULL) {
		return;
	}

	g_Shot.pos += frames;

	if (g_Shot.pos >= g_Shot.frames) {
		sndFileStop();
	}
}

void sndFileStop(void)
{
	free(g_Shot.samples);
	memset(&g_Shot, 0, sizeof(g_Shot));
}