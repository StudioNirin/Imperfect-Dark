#!/usr/bin/env python3
"""Compile a model pack's files into a C table embedded in the executable.

The DB-Shotgun's two fitted meshes and their pictures are part of the weapon,
not an optional download. Mirroring tools/langpack/build.py --embed, this
writes a generated C file whose byte arrays are added to the game's sources at
configure time. The game mounts them in an in-memory directory and serves them
from modelpackFindN64(), so no folder, config key or updater asset is needed.

Usage: embed.py --src model-packs/dbshotgun/n64 --embed <out.c> [--quiet]
"""

import argparse
import os
import sys


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--src', required=True, help='folder whose files are embedded')
    p.add_argument('--embed', required=True, help='generated C output')
    p.add_argument('--quiet', action='store_true')
    args = p.parse_args()

    files = []
    for root, dirs, names in os.walk(args.src):
        dirs.sort()
        for name in sorted(names):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, args.src).replace(os.sep, '/')
            files.append((rel, open(path, 'rb').read()))

    os.makedirs(os.path.dirname(os.path.abspath(args.embed)), exist_ok=True)
    with open(args.embed, 'w', encoding='utf-8') as out:
        out.write('/* Generated by tools/modelpack/embed.py - do not edit. */\n')
        out.write('#include "modelpackembed.h"\n\n')
        for i, (rel, data) in enumerate(files):
            out.write(f'static const unsigned char g_EmbedData{i}[] = {{\n')
            for j in range(0, len(data), 16):
                out.write('    ' + ','.join(f'0x{b:02x}' for b in data[j:j + 16]) + ',\n')
            out.write('};\n\n')
        out.write('const struct embeddedmodelfile g_EmbeddedModelFiles[] = {\n')
        for i, (rel, data) in enumerate(files):
            out.write(f'    {{ "{rel}", g_EmbedData{i}, {len(data)} }},\n')
        out.write('};\n')
        out.write(f'const int g_EmbeddedModelNumFiles = {len(files)};\n')

    if not args.quiet:
        print(f'embed: {len(files)} files, {sum(len(d) for _, d in files)} bytes -> {args.embed}')


if __name__ == '__main__':
    sys.exit(main())
